"""
Metropolitan Museum of Art Inventory Standardization Script

This script performs data standardization on a TSV file containing
Metropolitan Museum of Art collection objects.

FIXITY CHECKS (for archival integrity):
=====================================
INPUT FILE:
  Filename: met_inventory.tsv
  MD5:    6ec5bfc2d979ad12eb3343149beb8617
  SHA256: 33c53888daa063ca9697f4a82f15cd2d047afbce1ccb21c235e9c4ae9509d547

OUTPUT FILE (generated by this script):
  Filename: met_inventory_standardized.tsv
  MD5:    [To be calculated and verified]
  SHA256: [To be calculated and verified]

TRANSFORMATIONS PERFORMED:
==========================
1. Remove leading/trailing whitespace from all cells
2. Replace NaN/empty values with empty strings for consistency
3. Normalize column names by stripping whitespace
4. Sort records chronologically by Object Date (earliest to latest)
   - Records without dates are placed at the end
5. Ensure consistent URL formatting

DATA QUALITY STATISTICS:
========================
- Total records: 300
- Records with missing titles: 25
- Records with missing dates: 11

USAGE:
  python3 standardize_met_inventory.py <input_file> <output_file>

EXAMPLE:
  python3 standardize_met_inventory.py met_inventory.tsv met_inventory_standardized.tsv
"""

import sys
import hashlib
import pandas as pd
from datetime import datetime
import re


def calculate_md5(filepath):
    """Calculate MD5 checksum of a file."""
    md5_hash = hashlib.md5()
    with open(filepath, "rb") as f:
        for chunk in iter(lambda: f.read(4096), b""):
            md5_hash.update(chunk)
    return md5_hash.hexdigest()


def calculate_sha256(filepath):
    """Calculate SHA256 checksum of a file."""
    sha256_hash = hashlib.sha256()
    with open(filepath, "rb") as f:
        for chunk in iter(lambda: f.read(4096), b""):
            sha256_hash.update(chunk)
    return sha256_hash.hexdigest()


def extract_sort_key(date_str):
    """
    Extract a sortable key from a date string.
    Returns tuple of (year, original_string) for sorting.
    Non-dated entries are assigned year 9999 to appear at the end.
    """
    if not date_str or date_str.strip() == '':
        return (9999, '')
    
    # Extract all numeric sequences
    numbers = re.findall(r'\d+', date_str)
    if numbers:
        first_year = int(numbers[0])
        return (first_year, date_str)
    
    return (9999, date_str)


def standardize_tsv(input_file, output_file):
    """
    Main standardization function.
    
    Args:
        input_file (str): Path to input TSV file
        output_file (str): Path to output TSV file
    """
    
    print("=" * 70)
    print("METROPOLITAN MUSEUM OF ART INVENTORY STANDARDIZATION")
    print("=" * 70)
    print()
    
    # Calculate input file checksums
    print(f"Reading input file: {input_file}")
    input_md5 = calculate_md5(input_file)
    input_sha256 = calculate_sha256(input_file)
    
    print(f"  MD5:    {input_md5}")
    print(f"  SHA256: {input_sha256}")
    print()
    
    # Read TSV file
    print("Loading TSV file...")
    df = pd.read_csv(input_file, sep='\t')
    print(f"  Loaded {len(df)} records with {len(df.columns)} columns")
    print()
    
    # Step 1: Remove whitespace from all cells
    print("Step 1: Removing whitespace from all cells...")
    df = df.map(lambda x: x.strip() if isinstance(x, str) else x)
    print("  ✓ Complete")
    print()
    
    # Step 2: Replace NaN values with empty strings
    print("Step 2: Standardizing missing values...")
    initial_nans = df.isna().sum().sum()
    df = df.fillna('')
    final_nans = df.isna().sum().sum()
    print(f"  ✓ Replaced {initial_nans} NaN values with empty strings")
    print()
    
    # Step 3: Normalize column names
    print("Step 3: Normalizing column names...")
    original_cols = list(df.columns)
    df.columns = [col.strip() for col in df.columns]
    normalized_cols = list(df.columns)
    print(f"  Columns: {normalized_cols}")
    print("  ✓ Complete")
    print()
    
    # Step 4: Sort by Object Date
    print("Step 4: Sorting records chronologically...")
    df['__sort_key'] = df['Object Date'].apply(extract_sort_key)
    df = df.sort_values('__sort_key')
    df = df.drop('__sort_key', axis=1)
    df = df.reset_index(drop=True)
    print(f"  ✓ Records sorted by Object Date (earliest to latest)")
    print()
    
    # Step 5: Ensure consistent URL format
    print("Step 5: Normalizing URL format...")
    df['Link Resource'] = df['Link Resource'].apply(
        lambda x: x.strip() if isinstance(x, str) else x
    )
    print("  ✓ Complete")
    print()
    
    # Data quality statistics
    print("Data Quality Statistics:")
    print(f"  Total records: {len(df)}")
    print(f"  Records with missing titles: {(df['Title'] == '').sum()}")
    print(f"  Records with missing dates: {(df['Object Date'] == '').sum()}")
    print()
    
    # Save standardized file
    print(f"Writing output file: {output_file}")
    df.to_csv(output_file, sep='\t', index=False, quoting=1)
    print("  ✓ File written")
    print()
    
    # Calculate output file checksums
    print("Calculating output file checksums...")
    output_md5 = calculate_md5(output_file)
    output_sha256 = calculate_sha256(output_file)
    print(f"  MD5:    {output_md5}")
    print(f"  SHA256: {output_sha256}")
    print()
    
    # Print summary
    print("=" * 70)
    print("STANDARDIZATION COMPLETE")
    print("=" * 70)
    print()
    print("FIXITY CHECK SUMMARY:")
    print(f"  Input file (met_inventory.tsv):")
    print(f"    MD5:    {input_md5}")
    print(f"    SHA256: {input_sha256}")
    print()
    print(f"  Output file ({output_file}):")
    print(f"    MD5:    {output_md5}")
    print(f"    SHA256: {output_sha256}")
    print()
    print(f"Timestamp: {datetime.now().isoformat()}")
    print("=" * 70)
    
    return {
        'input_file': input_file,
        'input_md5': input_md5,
        'input_sha256': input_sha256,
        'output_file': output_file,
        'output_md5': output_md5,
        'output_sha256': output_sha256,
        'records_processed': len(df),
        'timestamp': datetime.now().isoformat()
    }


if __name__ == '__main__':
    if len(sys.argv) < 3:
        print("Usage: python3 standardize_met_inventory.py <input_file> <output_file>")
        print()
        print("Example:")
        print("  python3 standardize_met_inventory.py met_inventory.tsv met_inventory_standardized.tsv")
        sys.exit(1)
    
    input_file = sys.argv[1]
    output_file = sys.argv[2]
    
    try:
        result = standardize_tsv(input_file, output_file)
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
