#!/bin/bash
# Standardization and checksum verification script for Met Museum inventory

set -e

INPUT_FILE="/mnt/user-data/uploads/met_inventory.tsv"
OUTPUT_FILE="/mnt/user-data/outputs/met_inventory_standardized.tsv"
CHECKSUM_FILE="/mnt/user-data/outputs/CHECKSUMS.sha256"
REPORT_FILE="/mnt/user-data/outputs/standardization_report.md"

echo "=========================================="
echo "Met Museum Inventory TSV Standardization"
echo "=========================================="
echo ""

# Run Python standardization script
echo "[1/4] Running standardization script..."
python3 /mnt/user-data/outputs/standardize_met_inventory.py

echo ""
echo "[2/4] Generating checksums..."

# Create checksum file
cat > "$CHECKSUM_FILE" << 'EOF'
# Checksums for Met Museum Inventory Files
# Generated by standardization script
# Format: SHA-256 hash  filename

# SOURCE FILE
EOF

sha256sum "$INPUT_FILE" >> "$CHECKSUM_FILE"

echo "" >> "$CHECKSUM_FILE"
echo "# STANDARDIZED OUTPUT" >> "$CHECKSUM_FILE"
sha256sum "$OUTPUT_FILE" >> "$CHECKSUM_FILE"

echo "✓ Checksum manifest created: $CHECKSUM_FILE"
echo ""

echo "[3/4] Displaying checksums..."
echo ""
cat "$CHECKSUM_FILE"
echo ""

echo "[4/4] Verification instructions..."
echo ""
echo "To verify file integrity, use:"
echo ""
echo "  sha256sum -c CHECKSUMS.sha256"
echo ""
echo "Or verify individual files:"
echo ""
echo "  sha256sum -c <<< 'HASH  FILENAME'"
echo ""

echo "=========================================="
echo "Standardization Complete!"
echo "=========================================="
echo ""
echo "Output files:"
echo "  - met_inventory_standardized.tsv"
echo "  - CHECKSUMS.sha256"
echo "  - standardization_report.md"
echo "  - standardize_met_inventory.py (script used)"
echo ""
